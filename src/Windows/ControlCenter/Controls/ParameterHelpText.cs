    internal static string Describe(string title,IEnumerable<FrameworkElement> nearby)
    {
        string key=title.Trim();
        var text=descriptions.GetValueOrDefault(key);
        if(text==null){
            var entry=LumaWall.Contracts.FeaturePacks.Widgets.FirstOrDefault(p=>p.Entry.Title==key||p.Entry.Grid?.Title==key)?.Entry;
            text=(entry?.Title==key?entry.Description:entry?.Grid?.Description)??Meaning(key);
        }
        var inputs=nearby.SelectMany(element=>new[]{element}.Concat(Children(element))).OfType<EffectValueInput>();
        if(inputs.FirstOrDefault() is { Target: { } slider } input) {
            string range=UiLanguage.Format($"范围 {slider.Minimum.ToString("0.###",CultureInfo.InvariantCulture)}–{slider.Maximum.ToString("0.###",CultureInfo.InvariantCulture)}{input.Unit}");
            return text.Length==0?range:text+" "+range;
        }
        return text;
    }
