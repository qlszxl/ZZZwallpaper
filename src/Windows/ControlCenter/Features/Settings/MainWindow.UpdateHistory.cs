    private void InitializeUpdateHistory()
    {
        HistoryPanel.Children.Add(UtilityText(UiLanguage.Text("更新历史"),"UtilityHeading"));
        string currentVersion=ApplicationVersion;
        foreach(var release in UpdateHistory) {
            var content=new StackPanel {Spacing=16};
            var heading=new StackPanel {Spacing=8};
            var versionHeading = release.Version.StartsWith("0.", StringComparison.Ordinal)
                ? UiLanguage.Format($"v{release.Version} · 测试版 · {UiLanguage.Text(release.Title)}")
                : UiLanguage.Format($"v{release.Version} · 正式版 · {UiLanguage.Text(release.Title)}");
            heading.Children.Add(HistoryText(versionHeading,"UtilityHeading"));
            if(release.Date.Length>0)heading.Children.Add(HistoryText((release.Version==currentVersion?UiLanguage.Text("当前版本 · "):"")+release.Date));
            content.Children.Add(heading);
            var changes=new StackPanel {Spacing=12};
            foreach(string change in release.Changes) {
                var row=new Grid {ColumnSpacing=10};
                row.ColumnDefinitions.Add(new() {Width=GridLength.Auto});row.ColumnDefinitions.Add(new());
                row.Children.Add(HistoryText("•","UtilityLabel"));
                var text=HistoryText(UiLanguage.Text(change),"UtilityLabel");Grid.SetColumn(text,1);row.Children.Add(text);
                changes.Children.Add(row);
            }
            content.Children.Add(changes);
            HistoryPanel.Children.Add(UtilityCard(content));
        }
    }
    private static TextBlock HistoryText(string text,string style="UtilityHint")
    {
        var label=UtilityText(text,style);
        label.TextLineBounds=TextLineBounds.Full;label.LineHeight=0;
        label.TextWrapping=TextWrapping.Wrap;label.VerticalAlignment=VerticalAlignment.Top;
        return label;
    }
